RITE_DOCS_MAP_AUTO="${RITE_DOCS_MAP_AUTO:-true}"

# ---------------------------------------------------------------------------
# docs_map_path
#
# Echo the absolute path to the docs-map TSV file.
# The file lives at docs/docs-map.tsv (committed to the repo, not in .rite/).
# ---------------------------------------------------------------------------
docs_map_path() {
  local project_root="${RITE_PROJECT_ROOT:-.}"
  echo "${project_root}/docs/docs-map.tsv"
}

# ---------------------------------------------------------------------------
# _docs_map_is_adr_file FILE_PATH
#
# Returns 0 (true) when the given absolute path matches the ADR pattern:
#   docs/**/*adr*.md (case-insensitive), matching the find pattern used by
#   _collect_auto_docs() in lib/core/plan-issues.sh (~lines 131-132).
# Returns 1 (false) otherwise.
#
# We test only the basename (not the full path) so the pattern is consistent
# with the find-based discovery that uses -name, not -path.
# ---------------------------------------------------------------------------
_docs_map_is_adr_file() {
  local filepath="$1"
  local basename_only
  basename_only="$(basename "$filepath")"
  # Case-insensitive ADR match: filename contains "adr" in any case.
  # Use a case statement for bash 3.2 compatibility (no [[ =~ ]] with IGNORECASE).
  case "$basename_only" in
    *[Aa][Dd][Rr]*.md) return 0 ;;
    *)                  return 1 ;;
  esac
}

# ---------------------------------------------------------------------------
# _docs_map_heading_level LINE
#
# Echo the heading level (1-6) for a line that starts with one or more '#'.
# If the line is not a heading, echo empty string.
# ---------------------------------------------------------------------------
_docs_map_heading_level() {
  local line="$1"
  local hashes=""
  local rest="$line"
  # Count leading '#' characters (POSIX parameter expansion, bash 3.2 safe).
  while [ "${rest#\#}" != "$rest" ]; do
    hashes="${hashes}#"
    rest="${rest#\#}"
  done
  local level="${#hashes}"
  if [ "$level" -ge 1 ] && [ "$level" -le 6 ]; then
    echo "$level"
  else
    echo ""
  fi
}

# ---------------------------------------------------------------------------
# _docs_map_heading_text LINE
#
# Strip leading '#' chars and surrounding whitespace from a heading line.
# Also strip any embedded tab characters (per spec: "tabs stripped from
# heading text on write").
# ---------------------------------------------------------------------------
_docs_map_heading_text() {
  local line="$1"
  # Strip leading '#' characters
  while [ "${line#\#}" != "$line" ]; do
    line="${line#\#}"
  done
  # Strip leading whitespace (POSIX: ${var#"${var%%[! ]*}"}  is overkill; use
  # a simple loop for portability without sed — but actually sed is fine here
  # and simpler; the CLAUDE.md style note says SC2001 is disabled).
  # Strip leading spaces/tabs:
  line="${line# }"
  line="${line#	}"
  # Strip trailing spaces/tabs (simple approach: no trailing whitespace expected in headings)
  line="${line% }"
  line="${line%	}"
  # Strip all embedded tab characters (replace with spaces per spec intent):
  # Use parameter expansion loop — no sed dependency for this simple case.
  local result=""
  local char
  local i=0
  local len="${#line}"
  while [ "$i" -lt "$len" ]; do
    # Extract one character at position $i using bash substring expansion
    char="${line:$i:1}"
    if [ "$char" = "	" ]; then
      # tab → skip (strip per spec)
      true
    else
      result="${result}${char}"
    fi
    i=$((i + 1))
  done
  echo "$result"
}

# ---------------------------------------------------------------------------
# _docs_map_sha256
#
# Portable sha256: reads stdin, writes the hex digest to stdout.
# Tries shasum -a 256 first (present on macOS and most Linux distros via
# perl), then falls back to sha256sum (Linux coreutils).
# ---------------------------------------------------------------------------
_docs_map_sha256() {
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum | awk '{print $1}'
  else
    # No sha256 tool available: drain stdin and return a placeholder.
    cat > /dev/null; echo "none"
  fi
}

# ---------------------------------------------------------------------------
# _docs_map_section_fingerprint CONTENT
#
# Compute the sha256 fingerprint of CONTENT after normalizing:
#   - trailing whitespace stripped from each line
# Outputs the hex digest (64 characters).
# ---------------------------------------------------------------------------
_docs_map_section_fingerprint() {
  local content="$1"
  # Strip trailing whitespace from every line, then hash.
  printf '%s\n' "$content" | sed 's/[[:space:]]*$//' | _docs_map_sha256 || true
}

# ---------------------------------------------------------------------------
# docs_map_build
#
# Full rebuild of the docs-map TSV. Atomic: writes to a temp file and then
# mv's into place so concurrent readers never see a partial map.
#
# Inventory set (each only if present at build time):
#   1. docs/**/*.md  (recursive, sorted)
#   2. README.md     (project root)
#   3. CLAUDE.md     (project root)
#
# No-op guard: RITE_DOCS_MAP_AUTO is NOT checked here — docs_map_build always
# rebuilds. The auto-rebuild opt-out lives in docs_map_ensure.
# ---------------------------------------------------------------------------
docs_map_build() {
  local project_root="${RITE_PROJECT_ROOT:-.}"
  local map_file
  map_file="$(docs_map_path)"
  local docs_dir
  docs_dir="$(dirname "$map_file")"

  # Ensure docs/ directory exists (committed dir; mkdir -p is idempotent)
  mkdir -p "$docs_dir"

  # Capture HEAD SHA (no -e guard: git rev-parse HEAD fails only in a non-repo,
  # which is caught earlier by config.sh; || true keeps set -e from firing if
  # somehow invoked outside a repo in tests).
  local head_sha
  head_sha="$(git -C "$project_root" rev-parse HEAD 2>/dev/null || echo "unknown")"

  # ISO-8601 UTC timestamp for the header.
  # BSD date: date -u +%Y-%m-%dT%H:%M:%SZ
  # GNU date: date -u +%Y-%m-%dT%H:%M:%SZ  (identical format, both work)
  local built_ts
  built_ts="$(date -u +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u +%Y-%m-%dT%H:%M:%SZ)"

  # -------------------------------------------------------------------------
  # Load existing map rows into a cache temp file so unchanged sections carry
  # forward their tags/note without triggering an LLM call.
  # Cache format (tab-separated): rel_path <TAB> heading_text <TAB> fingerprint <TAB> tags <TAB> note
  # Lookup: awk -v rp=X -v ht=Y searches by (rel_path, heading_text).
  # -------------------------------------------------------------------------
  local _cache_file=""
  local tmp_file=""
  if [ -f "$map_file" ]; then
    _cache_file="$(mktemp "${docs_dir}/docs-map-cache.XXXXXX" 2>/dev/null || true)"
    if [ -n "$_cache_file" ]; then
      awk -F'\t' '/^#/{next} NF>=6{
        tags = (NF>=9) ? $9 : "-"
        note = (NF>=10) ? $10 : "-"
        print $1 "\t" $5 "\t" $6 "\t" tags "\t" note
      }' "$map_file" > "$_cache_file" 2>/dev/null || true
    fi
  fi

  # Write to temp file for atomic replace
  tmp_file="$(mktemp "${docs_dir}/docs-map.tsv.XXXXXX")"

  # Line 1: comment header
  printf '# docs-map v4 sha=%s built=%s\n' "$head_sha" "$built_ts" > "$tmp_file"

  # -------------------------------------------------------------------------
  # Collect inventory: docs/**/*.md + README.md + CLAUDE.md
  # Use a while-read loop for bash 3.2 compatibility (no mapfile/readarray).
  # -------------------------------------------------------------------------
  local -a inventory_files=()
  local _f

  # 1. docs/**/*.md — find all .md files under docs/ sorted alphabetically
  if [ -d "${project_root}/docs" ]; then
    while IFS= read -r _f; do
      inventory_files+=("$_f")
    done < <(find "${project_root}/docs" -name "*.md" -type f 2>/dev/null | sort -u || true)
  fi

  # 2. README.md (project root, if present)
  if [ -f "${project_root}/README.md" ]; then
    inventory_files+=("${project_root}/README.md")
  fi

  # 3. CLAUDE.md (project root, if present)
  if [ -f "${project_root}/CLAUDE.md" ]; then
    inventory_files+=("${project_root}/CLAUDE.md")
  fi

  # -------------------------------------------------------------------------
  # Process each file: enumerate heading-delimited sections, compute a
  # content fingerprint per section, and emit one TSV row per section.
  #
  # Section boundaries: a valid Markdown heading line (outside a fenced code
  # block) starts a new section. The heading line is the first line of the
  # new section's content (included in its fingerprint).
  #
  # Preamble (lines before the first heading) is emitted as its own row when
  # it contains non-empty content. Headingless files always emit one row.
  # -------------------------------------------------------------------------
  local file_path
  for file_path in "${inventory_files[@]+"${inventory_files[@]}"}"; do
    # Compute project-relative path (strip leading project_root + /)
    local rel_path="${file_path#"${project_root}/"}"

    # Determine ADR flag and doc type
    local adr_flag="-"
    local doc_type="other"   # default for top-level files (README.md, CLAUDE.md)
    if _docs_map_is_adr_file "$file_path"; then
      adr_flag="adr"
      doc_type="adr"
    else
      case "$rel_path" in
        docs/*) doc_type="feature" ;;
        *)      doc_type="other" ;;
      esac
    fi
    local rubric="-"

    # Per-section state: current section's heading and accumulated content.
    local _sec_h_level=""   # "" = preamble or headingless
    local _sec_h_text=""
    local _sec_content=""   # accumulates lines, joined with newlines
    local _rows_written=0
    local _in_fence=0

    # Helper (inline via function call): flush the current section to tmp_file.
    # Emits a row when: the section has a heading (always) OR the preamble
    # content is non-empty. Carries forward tags/note from _cache_file when
    # the section fingerprint is unchanged (fingerprint-gated tag preservation).
    _flush_section() {
      local _h_lv="$1" _h_tx="$2" _content="$3" _rp="$4" _sha="$5" _af="$6"
      local _dtype="${7:-other}" _rubric="${8:--}"
      local _emit=0
      if [ -n "$_h_lv" ]; then
        # Heading section — always emit
        _emit=1
      elif [ -n "$_content" ]; then
        # Preamble/headingless — emit only when there is content
        _emit=1
      fi
      if [ "$_emit" -eq 1 ]; then
        local _fp
        _fp="$(_docs_map_section_fingerprint "$_content")"
        # Carry forward tags/note when fingerprint matches the cached row.
        # Cache lookup uses awk for reliable tab handling (bash 3.2 compatible).
        local _tags="-" _note="-"
        if [ -n "$_cache_file" ] && [ -f "$_cache_file" ]; then
          local _cached
          _cached="$(awk -F'\t' -v rp="$_rp" -v ht="$_h_tx" -v fp="$_fp" \
            '$1==rp && $2==ht && $3==fp {print $4 "\t" $5; exit}' \
            "$_cache_file" 2>/dev/null || true)"
          if [ -n "$_cached" ]; then
            local _ct _cn
            _ct="${_cached%%	*}"
            _cn="${_cached#*	}"
            # Only carry forward non-empty, non-sentinel cached tags
            if [ -n "$_ct" ] && [ "$_ct" != "-" ]; then
              _tags="$_ct"
              _note="${_cn:--}"
            fi
          fi
        fi
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
          "$_rp" "$_sha" "$_af" "$_h_lv" "$_h_tx" "$_fp" "$_dtype" "$_rubric" "$_tags" "$_note" >> "$tmp_file"
        _rows_written=$((_rows_written + 1))
      fi
    }

    local raw_line h_level h_text
    while IFS= read -r raw_line || [ -n "$raw_line" ]; do
      # Fence boundary detection: lines starting with ``` or ~~~.
      case "$raw_line" in
        '```'* | '~~~'*)
          if [ "$_in_fence" -eq 0 ]; then
            _in_fence=1
          else
            _in_fence=0
          fi
          # Fence boundary lines are content — append and continue.
          if [ -z "$_sec_content" ]; then
            _sec_content="$raw_line"
          else
            _sec_content="${_sec_content}
${raw_line}"
          fi
          continue
          ;;
      esac

      if [ "$_in_fence" -eq 0 ]; then
        # Outside a fence: check for a valid Markdown heading.
        case "$raw_line" in
          '#'*)
            h_level="$(_docs_map_heading_level "$raw_line")"
            if [ -n "$h_level" ]; then
              # Valid heading — flush the current section, start a new one.
              h_text="$(_docs_map_heading_text "$raw_line")"
              _flush_section "$_sec_h_level" "$_sec_h_text" "$_sec_content" \
                "$rel_path" "$head_sha" "$adr_flag" "$doc_type" "$rubric"
              _sec_h_level="$h_level"
              _sec_h_text="$h_text"
              _sec_content="$raw_line"   # heading line is first content of new section
              continue
            fi
            ;;
        esac
      fi

      # All other lines (body, fence content, non-heading # lines) accumulate.
      if [ -z "$_sec_content" ]; then
        _sec_content="$raw_line"
      else
        _sec_content="${_sec_content}
${raw_line}"
      fi
    done < "$file_path"

    # Flush the last section.
    _flush_section "$_sec_h_level" "$_sec_h_text" "$_sec_content" \
      "$rel_path" "$head_sha" "$adr_flag" "$doc_type" "$rubric"

    # Every file must have at least one row (headingless empty files fall here).
    if [ "$_rows_written" -eq 0 ]; then
      local _fp
      _fp="$(_docs_map_section_fingerprint "")"
      printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
        "$rel_path" "$head_sha" "$adr_flag" "" "" "$_fp" "$doc_type" "$rubric" "-" "-" >> "$tmp_file"
    fi
  done

  # Unset the inner helper to avoid leaking it into the caller's shell.
  unset -f _flush_section 2>/dev/null || true

  # Clean up cache temp file (build complete)
  if [ -n "$_cache_file" ] && [ -f "$_cache_file" ]; then
    rm -f "$_cache_file"
    _cache_file=""
  fi

  # Atomic replace
  mv "$tmp_file" "$map_file"
  tmp_file=""  # already moved

  # Migrate: remove legacy .rite/state/docs-map.tsv if it still exists.
  # The file moved to docs/docs-map.tsv (committed path); the old location
  # is gitignored, so removing it is safe and prevents stale reads.
  local _legacy_map="${project_root}/.rite/state/docs-map.tsv"
  if [ -f "$_legacy_map" ]; then
    rm -f "$_legacy_map"
  fi
}

# ---------------------------------------------------------------------------
# docs_map_ensure
#
# Rebuild the docs-map if it is missing. Silent except for one verbose-level
# line when a rebuild occurs.
#
# Does NOT rebuild on HEAD-SHA mismatch: later cluster-B issues update
# last_verified_sha per-file, and an auto-rebuild would clobber those records.
#
# Respects RITE_DOCS_MAP_AUTO: when set to "false" (or "0"), skips rebuild
# entirely and returns 0.
# ---------------------------------------------------------------------------
docs_map_ensure() {
  local map_file
  map_file="$(docs_map_path)"

  # Honour opt-out flag
  local auto_enabled="${RITE_DOCS_MAP_AUTO:-true}"
  if [ "$auto_enabled" = "false" ] || [ "$auto_enabled" = "0" ]; then
    return 0
  fi

  # Rebuild when the map is missing OR is a pre-v4 format.
  local _needs_rebuild=0
  if [ ! -f "$map_file" ]; then
    _needs_rebuild=1
  else
    local _header
    _header="$(head -1 "$map_file" 2>/dev/null || true)"
    case "$_header" in
      "# docs-map v4"*) ;;  # current format — no rebuild needed
      *) _needs_rebuild=1 ;; # v1, v2, or other old format
    esac
  fi
  if [ "$_needs_rebuild" -eq 1 ]; then
    if declare -f verbose_info >/dev/null 2>&1; then
      verbose_info "docs-map: rebuilding missing/pre-v4 map → $(basename "$map_file")"
    fi
    docs_map_build
  fi
}

# ---------------------------------------------------------------------------
# docs_map_populate_tags
#
# LLM enrichment pass: for each map row where tags="-" (new or fingerprint-
# changed section), call the triage model to assign tags and a short note.
# Rows whose tags are already set (carried forward by docs_map_build when the
# fingerprint is unchanged) are skipped — this is the fingerprint-gate.
#
# The triage model (haiku) performs bucket classification: given heading text
# and source file path it emits JSON: {"tags": ["t1", "t2"], "note": "..."}
#
# Rule 31/32: uses provider_resolve_model triage — never passes "" as model.
# Graceful degradation: if the provider isn't loaded or jq is absent, returns 0.
# Atomic write: reads map → enriches in memory → mv temp → map.
# ---------------------------------------------------------------------------
docs_map_populate_tags() {
  # Guard: provider functions required (caller must have called load_provider)
  if ! declare -f provider_run_prompt_with_timeout >/dev/null 2>&1; then
    return 0
  fi
  if ! declare -f provider_resolve_model >/dev/null 2>&1; then
    return 0
  fi

  local map_file
  map_file="$(docs_map_path)"
  [ -f "$map_file" ] || return 0

  local _map_dir
  _map_dir="$(dirname "$map_file")"
  local _tmp=""
  _tmp="$(mktemp "${_map_dir}/docs-map.tsv.XXXXXX" 2>/dev/null)" || return 0

  # Copy comment header unchanged
  head -1 "$map_file" > "$_tmp"

  local _changes=0
  local _f _sha _adr _hl _ht _fp _dtype _rubric _tags _note
  # Use IFS=$'\001' (SOH, non-whitespace) with awk preprocessing to avoid bash's
  # IFS-whitespace tab-collapsing, which corrupts rows with consecutive empty fields
  # (e.g. preamble/headingless rows where heading_level and heading_text are both empty).
  while IFS=$'\001' read -r _f _sha _adr _hl _ht _fp _dtype _rubric _tags _note; do
    # fingerprint-gate: only enrich rows where tags is "-" or absent
    if [ "${_tags:-}" != "-" ] && [ -n "${_tags:-}" ]; then
      printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
        "$_f" "$_sha" "${_adr:--}" "${_hl:-}" "${_ht:-}" "$_fp" \
        "${_dtype:-other}" "${_rubric:--}" "$_tags" "${_note:--}" >> "$_tmp"
      continue
    fi

    # Build a triage prompt from heading text and file path
    local _prompt
    _prompt="Classify this documentation section. Output only JSON with no prose.
Format: {\"tags\": [\"tag1\", \"tag2\"], \"note\": \"short description max 80 chars\"}
Rules: 1-3 concise kebab-case tags (1-3 words each). Tags describe what the section is about.

File: ${_f}
Heading: ${_ht:-<untitled>}"

    local _result=""
    _result="$(provider_run_prompt_with_timeout \
      "$_prompt" \
      "$(provider_resolve_model triage)" \
      true \
      "${RITE_DOC_CLAUDE_TIMEOUT:-30}" \
      2>/dev/null)" || true

    local _new_tags="-" _new_note="-"
    if [ -n "$_result" ] && command -v jq >/dev/null 2>&1; then
      # Strip fenced JSON (models frequently wrap output in ```json ... ``` fences;
      # jq fails on fenced input, causing tags to stay "-" and re-triggering LLM on every run)
      local _result_clean
      _result_clean="$(printf '%s' "$_result" | sed 's/^```[a-zA-Z]*$//' | sed 's/^```$//' || true)"
      [ -z "$_result_clean" ] && _result_clean="$_result"
      _new_tags="$(printf '%s' "$_result_clean" | jq -r '(.tags // []) | map(select(. != "")) | join(", ")' 2>/dev/null || true)"
      _new_note="$(printf '%s' "$_result_clean" | jq -r '(.note // "-") | gsub("\t"; " ")' 2>/dev/null || true)"
      [ -z "$_new_tags" ] && _new_tags="-"
      [ -z "$_new_note" ] && _new_note="-"
      # Sanitize: strip tabs and newlines (both corrupt TSV columns)
      _new_tags="$(printf '%s' "$_new_tags" | tr '\t\n' '  ')"
      _new_note="$(printf '%s' "$_new_note" | tr '\t\n' '  ')"
    fi

    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
      "$_f" "$_sha" "${_adr:--}" "${_hl:-}" "${_ht:-}" "$_fp" \
      "${_dtype:-other}" "${_rubric:--}" "$_new_tags" "$_new_note" >> "$_tmp"
    [ "$_new_tags" != "-" ] && _changes=$((_changes + 1))
  done < <(awk -F'\t' '/^#/{next}{printf "%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\n",$1,(NF>=2)?$2:"",(NF>=3)?$3:"-",(NF>=4)?$4:"",(NF>=5)?$5:"",(NF>=6)?$6:"",(NF>=7)?$7:"other",(NF>=8)?$8:"-",(NF>=9)?$9:"-",(NF>=10)?$10:"-"}' "$map_file" || true)

  if [ "$_changes" -gt 0 ]; then
    mv "$_tmp" "$map_file"
    _tmp=""  # already moved
  else
    rm -f "$_tmp"
    _tmp=""
  fi
  return 0
}

# ---------------------------------------------------------------------------
# docs_map_tag_section_by_pointer TARGET TAG
#
# Given a pointer of the form "file.md#Heading Text" and a tag name, find
# the map row whose file_path basename matches "file.md" and whose
# heading_text matches "Heading Text", then add TAG to that row's tags column.
# Idempotent: no-op when the tag is already present. Atomic write.
#
# Used by reconcile_tag_index to write coverage-check results into the map
# instead of directly into tag-index.md.
#
# Arguments:
#   $1 — target of the form "file.md#Heading Text" (FIRST # is the separator)
#   $2 — tag name to add
# ---------------------------------------------------------------------------
docs_map_tag_section_by_pointer() {
  local _target="$1"
  local _tag="$2"

  [ -z "$_target" ] && return 1
  [ -z "$_tag" ] && return 1

  # Split on the FIRST '#' (same logic as tag_index_add_coverage_pointer)
  local _file="${_target%%#*}"
  local _heading="${_target#*#}"
  if [ -z "$_file" ] || [ -z "$_heading" ] || [ "$_file" = "$_target" ]; then
    return 1
  fi

  local map_file
  map_file="$(docs_map_path)"
  [ -f "$map_file" ] || return 1

  local _map_dir
  _map_dir="$(dirname "$map_file")"
  local _tmp=""
  _tmp="$(mktemp "${_map_dir}/docs-map.tsv.XXXXXX" 2>/dev/null)" || return 1

  # Copy comment header unchanged
  head -1 "$map_file" > "$_tmp"

  local _matched=0
  local _f _sha _adr _hl _ht _fp _dtype _rubric _tags _note
  # Use IFS=$'\001' (SOH, non-whitespace) with awk preprocessing to avoid bash's
  # IFS-whitespace tab-collapsing corruption for rows with consecutive empty fields.
  while IFS=$'\001' read -r _f _sha _adr _hl _ht _fp _dtype _rubric _tags _note; do
    # Match by file basename and heading text
    local _bname
    _bname="$(basename "$_f")"
    if [ "$_bname" = "$_file" ] && [ "$_ht" = "$_heading" ]; then
      _matched=1
      # Add tag if not already present
      if [ "${_tags:-}" = "-" ] || [ -z "${_tags:-}" ]; then
        _tags="$_tag"
      else
        # Check for exact tag (word-boundary: split on ", " and match whole token)
        local _already=0
        local _t
        # portable: use awk for reliable split instead of IFS tricks
        _already="$(printf '%s' "$_tags" | awk -F', ' -v tag="$_tag" \
          'BEGIN{found=0} {for(i=1;i<=NF;i++) if($i==tag){found=1}} END{print found}' \
          2>/dev/null || echo "0")"
        if [ "$_already" != "1" ]; then
          _tags="${_tags}, ${_tag}"
        fi
      fi
    fi
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
      "$_f" "$_sha" "${_adr:--}" "${_hl:-}" "${_ht:-}" "$_fp" \
      "${_dtype:-other}" "${_rubric:--}" "${_tags:--}" "${_note:--}" >> "$_tmp"
  done < <(awk -F'\t' '/^#/{next}{printf "%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\n",$1,(NF>=2)?$2:"",(NF>=3)?$3:"-",(NF>=4)?$4:"",(NF>=5)?$5:"",(NF>=6)?$6:"",(NF>=7)?$7:"other",(NF>=8)?$8:"-",(NF>=9)?$9:"-",(NF>=10)?$10:"-"}' "$map_file" || true)

  mv "$_tmp" "$map_file"
  _tmp=""  # already moved
  [ "$_matched" -eq 1 ] || return 1
  return 0
}

# ---------------------------------------------------------------------------
# docs_map_render_tag_index
#
# Render docs/architecture/tag-index.md from the map's tags column.
# For each section row with non-empty tags, adds a pointer under each tag's
# heading in tag-index.md via the existing tag_index_ensure_heading /
# tag_index_add_pointer write helpers (section-safe, idempotent).
#
# Calling reconcile_tag_index → docs_map_tag_section_by_pointer (writes to
# map) → docs_map_render_tag_index (renders tag-index.md from map) keeps
# tag-index.md as a generated view of the map rather than an independently
# maintained store.
#
# Graceful degradation: returns 0 when the map is absent or the write helpers
# are not loaded.
# ---------------------------------------------------------------------------
docs_map_render_tag_index() {
  local map_file
  map_file="$(docs_map_path)"
  [ -f "$map_file" ] || return 0

  # Write helpers from tag-index.sh must be available
  if ! declare -f tag_index_ensure_heading >/dev/null 2>&1; then
    return 0
  fi
  if ! declare -f tag_index_add_pointer >/dev/null 2>&1; then
    return 0
  fi

  # Ensure tag-index.md file exists (bootstrap scaffold when missing)
  if declare -f tag_index_ensure_file >/dev/null 2>&1; then
    tag_index_ensure_file 2>/dev/null || true
  fi

  local _f _sha _adr _hl _ht _fp _dtype _rubric _tags _note
  # Use IFS=$'\001' (SOH, non-whitespace) with awk preprocessing to avoid bash's
  # IFS-whitespace tab-collapsing corruption for rows with consecutive empty fields.
  while IFS=$'\001' read -r _f _sha _adr _hl _ht _fp _dtype _rubric _tags _note; do
    # Skip rows with no tags or sentinel tags
    [ "${_tags:-}" = "-" ] || [ -z "${_tags:-}" ] && continue
    # Skip rows with no heading text (preamble or headingless sections)
    [ -z "${_ht:-}" ] && continue

    local _short
    _short="$(basename "$_f")"

    # Split tags on ", " and add each to the index.
    # printf '%s\n' ensures a trailing newline so while-read processes the last tag
    # (printf '%s' without a trailing newline causes read to return non-zero on the
    # final token, skipping it — critical for single-tag rows).
    local _tag
    while IFS= read -r _tag; do
      _tag="${_tag# }"  # ltrim space (from "tag1, tag2" split)
      _tag="${_tag% }"  # rtrim space
      [ -z "$_tag" ] || [ "$_tag" = "-" ] && continue
      tag_index_ensure_heading "$_tag" 2>/dev/null || true
      tag_index_add_pointer "$_tag" "$_short" "$_ht" 2>/dev/null || true
    done < <(printf '%s\n' "$_tags" | tr ',' '\n' || true)
  done < <(awk -F'\t' '/^#/{next}{printf "%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\001%s\n",$1,(NF>=2)?$2:"",(NF>=3)?$3:"-",(NF>=4)?$4:"",(NF>=5)?$5:"",(NF>=6)?$6:"",(NF>=7)?$7:"other",(NF>=8)?$8:"-",(NF>=9)?$9:"-",(NF>=10)?$10:"-"}' "$map_file" || true)

  return 0
}

# ---------------------------------------------------------------------------
# docs_map_enforcing_tests DOC_PATH
#
# Parse <!-- sharkrite-enforced-by: path/a.bats, path/b.bats --> markers
# from DOC_PATH and echo each declared test path on its own line.
# Empty output when the doc has no markers or no path-shaped .bats tokens.
#
# DOC_PATH may be absolute or project-relative (resolved against RITE_PROJECT_ROOT).
# Multiple markers per doc are accumulated; multiple comma-separated paths per
# marker are each emitted on their own line.
#
# The grep is format-anchored: requires at least one [^[:space:]]+.bats token so
# a doc that merely *documents* the marker format (no real test path) produces no
# output. This is the #90 bare-prefix guard applied to doc-file parsing.
# ---------------------------------------------------------------------------
docs_map_enforcing_tests() {
  local doc_path="$1"
  local project_root="${RITE_PROJECT_ROOT:-.}"

  # Resolve to absolute path
  case "$doc_path" in
    /*) ;;
    *) doc_path="${project_root}/${doc_path}" ;;
  esac

  [ -f "$doc_path" ] || return 0

  # sharkrite-lint disable UNDOCUMENTED_RITE_VAR - Reason: RITE_MARKER_ENFORCED_BY is a marker constant defined in markers.sh, not a user config var; RITE_MARKER_* is the canonical prefix convention for marker constants (see markers.sh); _RITE_ prefix cannot be used; ledger is frozen per 2026-07-14 rule
  local _marker="${RITE_MARKER_ENFORCED_BY}"

  # Format-anchored grep: requires at least one [^[:space:]]+.bats token AND closing -->.
  # Requiring --> also rejects line-wrapped markers (multi-line comments where the
  # marker name and --> are on different lines). Per-entry case filter below rejects
  # non-.bats tokens (e.g. N/A) that share a line with a real .bats path.
  # The #90 bare-prefix guard applied to doc-file parsing.
  local _matched_line _value _entry
  while IFS= read -r _matched_line; do
    # Extract the value between "${_marker}:" and "-->"
    _value="${_matched_line#*${_marker}:}"
    _value="${_value%%-->*}"
    # Split comma-separated paths; default IFS strips leading/trailing whitespace;
    # case filter rejects non-.bats entries (e.g. N/A, empty trailing comma slot).
    while read -r _entry; do
      case "$_entry" in
        *.bats) printf '%s\n' "$_entry" ;;
      esac
    done < <(printf '%s\n' "$_value" | tr ',' '\n' || true)
  done < <(grep -E "<!--[[:space:]]*${_marker}:[^>]*[^[:space:]]+\.bats[^>]*-->" "$doc_path" 2>/dev/null || true)
  return 0
}

# ---------------------------------------------------------------------------
# docs_map_adr_links ADR_PATH
#
# Extract inline markdown links ([text](url)) from ADR_PATH, resolve relative
# paths against the ADR's directory, and emit the subset whose resolved paths
# appear as file_path entries in the docs map — one per line, deduplicated.
#
# External URLs (http/https/ftp/mailto), anchor-only links (#...), and links
# that resolve to files not in the map (code files, unknown paths) are excluded.
# URL fragments are stripped before resolution (foo.md#section → foo.md).
# Links inside fenced code blocks (``` ... ```) are excluded.
#
# ADR_PATH may be absolute or project-relative. Returns 0 with empty output
# when the ADR has no in-map links, the ADR file does not exist, or the
# docs map is absent. No LLM calls.
# ---------------------------------------------------------------------------
docs_map_adr_links() {
  local adr_path="$1"
  local project_root="${RITE_PROJECT_ROOT:-.}"

  case "$adr_path" in
    /*) ;;
    *) adr_path="${project_root}/${adr_path}" ;;
  esac

  [ -f "$adr_path" ] || return 0

  local adr_dir
  adr_dir="$(dirname "$adr_path")"

  local map_file
  map_file="$(docs_map_path)"
  [ -f "$map_file" ] || return 0

  # Read all in-map file paths once (skip the comment header line, first col only).
  local _map_paths
  _map_paths="$(awk -F'\t' 'NR>1{print $1}' "$map_file" 2>/dev/null || true)"

  local _raw _link_no_frag _resolved _abs_dir _rel_path _emitted=""
  while IFS= read -r _raw; do
    # Skip external URLs and anchor-only links — not in-map by definition.
    case "$_raw" in
      http://* | https://* | ftp://* | mailto:* | '//'* | '#'*) continue ;;
    esac

    # Strip URL fragment (e.g. docs/foo.md#section → docs/foo.md).
    _link_no_frag="${_raw%%#*}"
    [ -n "$_link_no_frag" ] || continue

    # Resolve to absolute path.
    case "$_link_no_frag" in
      /*) _resolved="${project_root}${_link_no_frag}" ;;
      *)  _resolved="${adr_dir}/${_link_no_frag}" ;;
    esac

    # Normalize via cd/pwd to resolve ../ and ./ components.
    _abs_dir="$(cd "$(dirname "$_resolved")" 2>/dev/null && pwd)" || continue
    _resolved="${_abs_dir}/$(basename "$_resolved")"

    # Convert to project-relative path.
    _rel_path="${_resolved#"${project_root}/"}"

    # Emit only if in the docs map and not already emitted (dedup).
    if printf '%s\n' "$_map_paths" | grep -qxF "$_rel_path" 2>/dev/null; then
      if ! printf '%s\n' "$_emitted" | grep -qxF "$_rel_path" 2>/dev/null; then
        printf '%s\n' "$_rel_path"
        _emitted="${_emitted}${_rel_path}
"
      fi
    fi
  done < <(awk '/^```/{skip=!skip; next} !skip' "$adr_path" 2>/dev/null | \
           grep -oE '\[[^]]*\]\([^)]+\)' 2>/dev/null | \
           sed 's/^.*](//;s/)$//' 2>/dev/null || true)

  return 0
}
