# lib/utils/docs-map.sh
#
# Deterministic docs-map builder. Inventories user documentation —
#   docs/**/*.md, README.md, CLAUDE.md (each only if present)
# — into docs/docs-map.tsv (committed to the repo), recording each file's
# sections with content fingerprints and the HEAD SHA they were captured at.
#
# TSV format:
#   Line 1 (comment header): # docs-map v4 sha=<HEAD sha> built=<ISO-8601 UTC>
#   Remaining rows:           file_path<TAB>last_verified_sha<TAB>adr_flag<TAB>heading_level<TAB>heading_text<TAB>fingerprint<TAB>type<TAB>rubric<TAB>tags<TAB>note
#
# Columns:
#   file_path          — project-relative path, e.g. README.md
#   last_verified_sha  — HEAD SHA at build time (later cluster-B issues update per-file)
#   adr_flag           — "adr" or "-"
#   heading_level      — 1-6 (number of leading # characters), or empty for headingless sections
#   heading_text       — heading text with leading #s and whitespace stripped; tabs stripped;
#                        empty for preamble sections and headingless files
#   fingerprint        — sha256 of the normalized section content (heading line + body);
#                        normalization: trailing whitespace stripped per line
#   type               — "adr" (docs/**/*adr*.md), "feature" (other docs/**/*.md),
#                        "other" (README.md, CLAUDE.md)
#   rubric             — default "-"; future: pointer to a per-doc-type rubric file
#   tags               — comma-separated issue-routing tags for this section (e.g. "subshell, set-e");
#                        "-" when not yet generated; carried forward from previous build when
#                        fingerprint is unchanged (so unchanged sections never trigger an LLM call)
#   note               — short one-line description generated by the triage model; "-" when absent
#
# One row per heading-delimited section. Preamble content (before the first heading)
# and headingless files each get one row with empty heading_level and heading_text.
# Every file produces at least one row so it always appears in the inventory.
#
# No LLM involvement in the builder: docs_map_build is fully deterministic.
# LLM enrichment is a separate pass: docs_map_populate_tags (triage-role, haiku).
# No consent-mode gating: builds regardless of RITE_DOC_MODE.
#
# Public API:
#   docs_map_path              — echoes the absolute path to the TSV map file
#   docs_map_build             — full rebuild; atomic write via temp file + mv;
#                                migrates legacy .rite/state/docs-map.tsv on first run;
#                                carries forward tags/note for unchanged sections (by fingerprint)
#   docs_map_ensure            — rebuilds when map is missing or is pre-v4 format; no-op on SHA mismatch —
#                                cluster-B issues update last_verified_sha per-file and a
#                                full rebuild would clobber those audit records)
#   docs_map_populate_tags     — LLM enrichment pass: fills tags/note for rows where tags="-";
#                                uses provider_resolve_model triage; skips rows whose fingerprint
#                                is unchanged (tags/note carried forward by docs_map_build)
#   docs_map_tag_section_by_pointer — given "file.md#Heading" and a tag name, add the tag
#                                     to the matching map row's tags column (atomic update)
#   docs_map_render_tag_index  — render docs/architecture/tag-index.md from map tags column;
#                                merges map-derived entries with any existing file content
#   docs_map_enforcing_tests   — parse <!-- sharkrite-enforced-by: ... --> markers from a doc
#                                file; echo each declared test path on its own line
#   docs_map_adr_links         — extract inline markdown links from an ADR, resolve relative
#                                paths against the ADR's directory, and emit the subset that
#                                appears in the docs map — one per line, deduplicated
#
# Configuration:
#   RITE_DOCS_MAP_AUTO  (default: true) — set to "false" to suppress auto-rebuild
#                                         in docs_map_ensure

# ---------------------------------------------------------------------------
# Bootstrap: ensure RITE_PROJECT_ROOT and RITE_STATE_DIR are available.
